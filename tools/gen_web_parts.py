#!/usr/bin/env python3
"""Generates orchestration/WebParts.Generated.cs from upstream/Editor/NativeRemesherWindow.Parts.cs (drift check: the parts logic follows upstream by itself).

What is taken verbatim (every character of the model's logic): the tuning statics (hiddenCollapseWeight .. sewnShare), the weld comparers and AllSewn,
and the job lambda of RunParts -- the budget split, hidden-part visibility, turned parts, quad strips, copies, retries, collapse fallbacks, the shared bake.
What is NOT taken: the part gathering before it and FinishParts after it (they read and build Unity objects). Those are the hand-written
orchestration/WebParts.cs, whose members are fingerprinted by census/editor-members.json.
The only edits are the SUBSTITUTIONS below, each of which must match at least once: if upstream rewrites a line a substitution targets, this
script fails (and so does CI) instead of silently generating something different.
usage: gen_web_parts.py [--check] [Parts.cs]   (--check: exit 1 if the committed file differs from what upstream would generate)"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith('--')]
src = pathlib.Path(args[0] if args else root / 'upstream/Editor/NativeRemesherWindow.Parts.cs').read_text().split('\n')
out_path = root / 'orchestration/WebParts.Generated.cs'

def find(pattern, start=0):
    for i in range(start, len(src)):
        if re.search(pattern, src[i]): return i
    sys.exit(f'gen_web_parts: anchor not found in upstream: {pattern}')

# anchors (line indices)
lam_start = find(r'var run = new PartsRun \{ results = new List<RemeshResult>\(\) \};')
lam_end = find(r'^\s*return run;\s*$', lam_start)
close = find(r'^\s*\}, token\);\s*$', lam_end)
if close != lam_end + 1: sys.exit('gen_web_parts: the job lambda no longer ends "return run; }, token);"')
tune_start = find(r'public static float hiddenCollapseWeight')
# the doc comment above it starts at the first /// line of its block
while src[tune_start - 1].strip().startswith('///'): tune_start -= 1
tune_end = find(r'public static float sewnShare')
helper_start = find(r'sealed class WeldCellComparer')
while src[helper_start - 1].strip().startswith('///'): helper_start -= 1
helper_end = find(r'^\s*void FinishParts\(PartsRun run\)') - 1       # AllSewn ends just before FinishParts

SUBS = [  # (regex, replacement, minimum matches)
    (r'\bm_JobStage\b', 'job.stage', 1),
    (r'\bm_JobProgress\b', 'job.progress', 1),
    (r'\bm_JobWatch\b', 'c.watch', 1),
]

def sub(text, what):
    for pat, rep, minimum in SUBS:
        text, n = re.subn(pat, rep, text)
        if what == 'lambda' and n < minimum: sys.exit(f'gen_web_parts: substitution {pat!r} matched {n}x (needs >= {minimum}): upstream changed the code it rewrites')
    return text

lam = sub('\n'.join(src[lam_start:lam_end + 1]), 'lambda')
tune = '\n'.join(src[tune_start:tune_end + 1])
helpers = '\n'.join(src[helper_start:helper_end])
# the tuning block's last member is followed by AllSewn's doc comments in upstream: dropped above (they sit between sewnShare and the comparers)

text = f'''// <auto-generated>
// By tools/gen_web_parts.py from upstream/Editor/NativeRemesherWindow.Parts.cs. DO NOT EDIT: change the generator or upstream.
// The job lambda of RunParts, the tuning statics and AllSewn, as upstream wrote them (three identifier rewrites: m_JobStage, m_JobProgress, m_JobWatch).
// </auto-generated>
using System;
using System.Collections.Generic;
using UnityEngine;

namespace NativeRemesher.Web
{{
    public static partial class WebParts
    {{
{tune}

{helpers}

        /// <summary>The window's job lambda (RunParts): everything between gathering the parts and building the scene objects.</summary>
        static PartsRun SolveParts(PartsContext c)
        {{
            var settings = c.settings; var profile = c.profile; var autoProfile = c.autoProfile;
            var inputs = c.inputs; var areas = c.areas; var floors = c.floors; var pieces = c.pieces; var occludes = c.occludes;
            var materials = c.materials; var submeshes = c.submeshes; var rawUvs = c.rawUvs; var paints = c.paints; var names = c.names;
            var hiddenFewer = c.hiddenFewer; var bakeTexture = c.bakeTexture; var bakeNormals = c.bakeNormals; var bakeResolution = c.bakeResolution;
            var imageArray = c.imageArray; var normalImageArray = c.normalImageArray; var layerArray = c.layerArray;
            var job = c.job; var token = System.Threading.CancellationToken.None;
            {lam}
        }}
    }}
}}
'''
# Parallel.For over the parts runs on the caller's scheduler (the inline one in the browser build), exactly as upstream's BackgroundScheduler.Options does.
if '--check' in sys.argv:
    if not out_path.exists() or out_path.read_text() != text: print('DRIFT orchestration/WebParts.Generated.cs is stale: run tools/gen_web_parts.py and commit'); sys.exit(1)
    print('WebParts.Generated.cs is up to date with upstream'); sys.exit(0)
out_path.write_text(text); print(f'wrote {out_path.relative_to(root)}: lambda {lam_end - lam_start + 1} lines, tuning {tune_end - tune_start + 1}, helpers {helper_end - helper_start}')
